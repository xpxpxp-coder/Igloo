#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const readJson = (path) =>
  JSON.parse(readFileSync(resolve(root, path), "utf8"));
const identity = readJson("product/identity.json");
const tokens = readJson("product/design-tokens.json");
const check = process.argv.includes("--check");

if (identity.schema_version !== 1 || tokens.schema_version !== 1) {
  throw new Error("unsupported Snowman product schema version");
}

const requiredIdentity = [
  "company_name",
  "product_name",
  "command_center_name",
  "admin_name",
  "mobile_name",
  "cli_name",
  "short_name",
  "tagline",
  "public_domain",
  "support_email",
  "desktop_bundle_id",
  "desktop_release_tag",
  "desktop_app_bundle_name",
  "primary_deep_link_scheme",
  "legacy_deep_link_scheme",
];
for (const field of requiredIdentity) {
  if (typeof identity[field] !== "string" || !identity[field].trim()) {
    throw new Error(`product/identity.json requires ${field}`);
  }
}

const generatedHeader =
  "// Generated by scripts/generate-snowman-product.mjs. Do not edit.\n";
function typescriptLiteral(value, depth = 0) {
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number" || typeof value === "boolean") {
    return String(value);
  }
  if (!value || Array.isArray(value) || typeof value !== "object") {
    throw new Error(
      "Snowman product TypeScript generation only accepts objects",
    );
  }
  const indent = "  ".repeat(depth);
  const childIndent = "  ".repeat(depth + 1);
  const entries = Object.entries(value).map(([key, child]) => {
    if (!/^[A-Za-z_$][\w$]*$/.test(key)) {
      throw new Error(
        `Snowman product key is not a TypeScript identifier: ${key}`,
      );
    }
    return `${childIndent}${key}: ${typescriptLiteral(child, depth + 1)},`;
  });
  return `{\n${entries.join("\n")}\n${indent}}`;
}
const ts = `${generatedHeader}export const SNOWMAN_PRODUCT = ${typescriptLiteral(identity)} as const;\n\nexport const PRODUCT_NAME = SNOWMAN_PRODUCT.product_name;\nexport const COMMAND_CENTER_NAME = SNOWMAN_PRODUCT.command_center_name;\nexport const ADMIN_NAME = SNOWMAN_PRODUCT.admin_name;\nexport const PRODUCT_TAGLINE = SNOWMAN_PRODUCT.tagline;\n`;

const cssTokenName = (group, name) =>
  `--snowman-${group}-${name.replaceAll("_", "-")}`;
const cssLines = [];
for (const [group, values] of Object.entries(tokens)) {
  if (group === "schema_version") continue;
  for (const [name, value] of Object.entries(values)) {
    const rendered = group === "motion" ? `${value}ms` : value;
    const property = cssTokenName(group, name);
    cssLines.push(
      group === "font"
        ? `  ${property}:\n    ${rendered};`
        : `  ${property}: ${rendered};`,
    );
  }
}
const css = `/* Generated by scripts/generate-snowman-product.mjs. Do not edit. */\n:root {\n${cssLines.join("\n")}\n  --snowman-surface: var(--snowman-color-ice);\n  --snowman-surface-strong: var(--snowman-color-snow);\n  --snowman-text: var(--snowman-color-midnight);\n  --snowman-text-muted: var(--snowman-color-slate);\n  --snowman-accent: var(--snowman-color-glacier);\n}\n\n:root.dark,\n[data-theme="dark"] {\n  --snowman-surface: var(--snowman-color-night);\n  --snowman-surface-strong: var(--snowman-color-midnight);\n  --snowman-text: var(--snowman-color-ice);\n  --snowman-text-muted: var(--snowman-color-frost);\n  --snowman-accent: var(--snowman-color-glacier);\n}\n`;

const dartString = (value) => `'${String(value).replaceAll("'", "\\'")}'`;
const dart = `${generatedHeader.replace("//", "//")}abstract final class SnowmanProduct {\n  static const productName = ${dartString(identity.product_name)};\n  static const commandCenterName = ${dartString(identity.command_center_name)};\n  static const adminName = ${dartString(identity.admin_name)};\n  static const mobileName = ${dartString(identity.mobile_name)};\n  static const tagline = ${dartString(identity.tagline)};\n  static const publicDomain = ${dartString(identity.public_domain)};\n  static const supportEmail = ${dartString(identity.support_email)};\n  static const primaryDeepLinkScheme = ${dartString(identity.primary_deep_link_scheme)};\n  static const legacyDeepLinkScheme = ${dartString(identity.legacy_deep_link_scheme)};\n}\n\nabstract final class SnowmanColors {\n${Object.entries(
  tokens.color,
)
  .map(
    ([name, value]) =>
      `  static const ${name} = 0xFF${value.slice(1).toUpperCase()};`,
  )
  .join("\n")}\n}\n`;

const outputs = new Map([
  ["desktop/src/shared/product/identity.generated.ts", ts],
  ["web/src/shared/product/identity.generated.ts", ts],
  ["admin-web/src/product/identity.generated.ts", ts],
  ["desktop/src/shared/styles/generated/snowman-brand.generated.css", css],
  ["web/src/shared/styles/snowman-brand.generated.css", css],
  ["admin-web/src/snowman-brand.generated.css", css],
  ["mobile/lib/shared/product/identity.g.dart", dart],
]);

let stale = false;
for (const [path, content] of outputs) {
  const absolute = resolve(root, path);
  if (check) {
    let actual = "";
    try {
      actual = readFileSync(absolute, "utf8");
    } catch {
      // Report below with the same stale message as a changed file.
    }
    if (actual !== content) {
      console.error(`stale generated Snowman product file: ${path}`);
      stale = true;
    }
  } else {
    mkdirSync(dirname(absolute), { recursive: true });
    writeFileSync(absolute, content);
  }
}

if (stale) process.exit(1);
console.log(
  check
    ? "Snowman product files are current"
    : `Generated ${outputs.size} Snowman product files`,
);
